"""Generate terminal-compatible sRGB colors from the shared OKLCH palette."""

import argparse
import json
import math
import re
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "themes/tokyonight-night.oklch.json"
RGB = ROOT / ".config/nvim/tokyonight-night.json"
REX = ROOT / "themes/generated/Tokyo Night Night OKLCH"
ANSI = (
    "black",
    "red",
    "green",
    "yellow",
    "blue",
    "magenta",
    "cyan",
    "white",
    "black_bright",
    "red_bright",
    "green_bright",
    "yellow_bright",
    "blue_bright",
    "magenta_bright",
    "cyan_bright",
    "white_bright",
)


def linear_rgb(lightness, chroma, hue):
    angle = math.radians(hue)
    a, b = chroma * math.cos(angle), chroma * math.sin(angle)
    long = (lightness + 0.3963377774 * a + 0.2158037573 * b) ** 3
    medium = (lightness - 0.1055613458 * a - 0.0638541728 * b) ** 3
    short = (lightness - 0.0894841775 * a - 1.2914855480 * b) ** 3
    return (
        4.0767416621 * long - 3.3077115913 * medium + 0.2309699292 * short,
        -1.2684380046 * long + 2.6097574011 * medium - 0.3413193965 * short,
        -0.0041960863 * long - 0.7034186147 * medium + 1.7076147010 * short,
    )


def in_gamut(rgb):
    # Allow matrix/decimal rounding at the sRGB boundary.
    return all(-0.00001 <= channel <= 1.00001 for channel in rgb)


def oklch_to_hex(value):
    match = re.fullmatch(r"oklch\(([^()]+)\)", value)
    if not match:
        raise ValueError(f"Expected oklch(L C H), got {value!r}")
    lightness, chroma, hue = map(float, match[1].split())
    if not all(map(math.isfinite, (lightness, chroma, hue))):
        raise ValueError(f"Non-finite color: {value}")
    if not 0 <= lightness <= 1 or chroma < 0 or not 0 <= hue <= 360:
        raise ValueError(f"Invalid OKLCH channels: {value}")
    rgb = linear_rgb(lightness, chroma, hue)
    if not in_gamut(rgb):
        # Reduce chroma only: preserve perceptual lightness and hue.
        low, high = 0.0, chroma
        for _ in range(32):
            middle = (low + high) / 2
            if in_gamut(linear_rgb(lightness, middle, hue)):
                low = middle
            else:
                high = middle
        rgb = linear_rgb(lightness, low, hue)

    def encode(channel):
        channel = max(0.0, min(1.0, channel))
        srgb = (
            12.92 * channel
            if channel <= 0.0031308
            else 1.055 * channel ** (1 / 2.4) - 0.055
        )
        return math.floor(srgb * 255 + 0.5)

    return "#" + "".join(f"{encode(channel):02x}" for channel in rgb)


def resolve_palette(palette: dict[str, Any]) -> dict[str, Any]:
    """Resolve @dotted.path aliases and convert every OKLCH leaf to hex."""

    def resolve(value: Any, seen: tuple[str, ...] = ()) -> Any:
        if isinstance(value, dict):
            return {key: resolve(item, seen) for key, item in value.items()}
        if isinstance(value, list):
            return [resolve(item, seen) for item in value]
        if not isinstance(value, str):
            raise TypeError(f"Palette leaves must be color strings, got {value!r}")
        if value == "NONE":
            return value
        if value.startswith("@"):
            name = value[1:]
            if name in seen:
                raise ValueError(f"Cyclic palette alias: {name}")
            target = palette
            for part in name.split("."):
                target = target[part]
            return resolve(target, (*seen, name))
        return oklch_to_hex(value)

    return resolve(palette)


def outputs():
    try:
        source = json.loads(SOURCE.read_text())
        colors = resolve_palette(source["palette"])
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise ValueError(f"Cannot load palette {SOURCE}: {error}") from error
    header = "# Generated by scripts/generate_palette.py; edit themes/tokyonight-night.oklch.json.\n"
    theme = header + "\n".join(
        f"palette = {index}={colors['terminal'][name]}"
        for index, name in enumerate(ANSI)
    )
    for key, name in (
        ("background", "bg"),
        ("foreground", "fg"),
        ("cursor-color", "fg"),
        ("cursor-text", "bg"),
        ("selection-background", "bg_visual"),
        ("selection-foreground", "fg"),
    ):
        theme += f"\n{key} = {colors[name]}"
    return {RGB: json.dumps(colors, indent=2) + "\n", REX: theme + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Check generated files without writing"
    )
    args = parser.parse_args()
    try:
        generated = outputs()
    except ValueError as error:
        parser.error(str(error))
    stale = []
    for path, content in generated.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Stale generated palette files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
